"""
Backup API — manual database snapshots the owner can take and download.

  POST   /api/backup/create           — take a snapshot right now
  GET    /api/backup/list             — every backup on disk, newest first
  GET    /api/backup/download/{name}  — download one as a file
  DELETE /api/backup/{name}           — delete one

WHY THIS EXISTS ALONGSIDE THE AUTOMATIC BACKUP:
main.py takes a `startup_*.db` snapshot every time the app opens.  That covers
the upgrade accident — a bad migration — but not the human one.  Before the
owner does something they are nervous about (a big stock correction, a bulk
price edit, handing the PC to a technician) they want a snapshot they chose the
moment for.  Those are named `manual_*.db` and, unlike the automatic ones, are
NEVER pruned.  Only the app deletes automatic backups; only a person deletes
manual ones.

WHY sqlite3's BACKUP API AND NOT shutil.copy2:
The database runs in WAL mode, so recently committed data lives in
pharmacy.db-wal until a checkpoint folds it back in.  Copying pharmacy.db on
its own can therefore silently omit the newest sales.  conn.backup() reads
through the WAL and writes one self-contained file.  This is the same reasoning
as _backup_on_startup() in main.py — see its docstring for the full note.
"""
import re
import sqlite3
from datetime import datetime

from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.responses import FileResponse

from app.database import get_app_data_dir
from app.models.user import User
from app.services.auth_service import get_current_user
from app.services.licence import require_full_licence

router = APIRouter(prefix="/backup", tags=["Backup"])

# Taking or deleting a backup is an ownership action, not a counter action —
# the file contains every sale, patient and price the shop has ever recorded.
_BACKUP_ADMIN_ROLES = {"Owner", "Administrator"}

# A backup filename is only ever generated by this file or by
# _backup_on_startup(), so it always looks like  startup_20260812_204512.db
# or  manual_20260812_204512.db.  The optional _2 / _3 tail is the
# same-second collision suffix both writers add.  Anything else is rejected
# outright — see _safe_backup_path below for why that matters.
_BACKUP_NAME_RE = re.compile(r"^(startup|manual)_\d{8}_\d{6}(_\d+)?\.db$")


def _backup_dir():
    """The folder holding every backup; created on first use."""
    d = get_app_data_dir() / "backups"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _require_admin(current_user: User) -> None:
    """Owner / Administrator gate, shared by every write endpoint here."""
    if current_user.role.name not in _BACKUP_ADMIN_ROLES:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Only an Owner or Administrator can manage backups.",
        )


def _safe_backup_path(filename: str):
    """
    Turn a user-supplied filename into a path inside the backups folder.

    The filename arrives in the URL, so it is untrusted input.  Without this
    check a request for '..%2F..%2Fpharmacy.db' would walk out of the backups
    folder and hand back the LIVE database — or, on the delete endpoint,
    destroy it.  Two independent guards:

      1. the name must match the exact backup pattern (no slashes, no dots
         beyond the .db suffix can survive that regex), and
      2. the resolved path must still sit inside the backups folder.

    Either one alone would do; both together mean a mistake in one is not a
    security hole.
    """
    if not _BACKUP_NAME_RE.match(filename):
        raise HTTPException(status_code=400, detail="Invalid backup filename.")

    path = (_backup_dir() / filename).resolve()
    if path.parent != _backup_dir().resolve():
        raise HTTPException(status_code=400, detail="Invalid backup filename.")
    if not path.exists():
        raise HTTPException(status_code=404, detail="Backup not found.")
    return path


def _snapshot_to(dest_path) -> None:
    """
    Write a consistent copy of the live database to dest_path.

    sqlite3.Connection.backup() is safe to call while the app is serving
    requests: it takes a read lock per step rather than freezing the file, and
    it pulls in WAL content that has not been checkpointed yet.
    """
    db_path = get_app_data_dir() / "pharmacy.db"
    if not db_path.exists():
        raise HTTPException(status_code=404, detail="No database file to back up.")

    source = sqlite3.connect(str(db_path))
    try:
        dest = sqlite3.connect(str(dest_path))
        try:
            source.backup(dest)
        finally:
            dest.close()
    finally:
        source.close()


def _describe(path) -> dict:
    """One backup, as the Backup page shows it."""
    stat = path.stat()
    return {
        "filename":   path.name,
        # 'startup' = taken automatically when the app opened (auto-pruned to
        # the last 7).  'manual' = the owner pressed the button (kept forever).
        "kind":       "startup" if path.name.startswith("startup_") else "manual",
        "size_bytes": stat.st_size,
        "size_kb":    round(stat.st_size / 1024, 1),
        # Local time: this is read by a person looking for "the one from before
        # lunch", not by another machine, so IST-on-the-shop-PC is what helps.
        "created_at": datetime.fromtimestamp(stat.st_mtime).isoformat(),
    }


@router.post("/create", status_code=status.HTTP_201_CREATED)
def create_backup(current_user: User = Depends(get_current_user)):
    """
    Take a snapshot right now.  Owner / Administrator only.

    Named manual_<timestamp>.db so the startup pruner — which only ever globs
    startup_*.db — can never delete it.
    """
    _require_admin(current_user)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    dest = _backup_dir() / f"manual_{timestamp}.db"
    # Same-second collision guard as _backup_on_startup: an owner who presses
    # the button twice must get two files, not one overwritten one.
    counter = 2
    while dest.exists():
        dest = _backup_dir() / f"manual_{timestamp}_{counter}.db"
        counter += 1

    _snapshot_to(dest)

    info = _describe(dest)
    info["message"] = "Backup created successfully."
    return info


@router.get("/list")
def list_backups(current_user: User = Depends(get_current_user)):
    """
    Every backup on disk, newest first — both the automatic startup ones and
    the manual ones, so the Backup page shows the full recovery picture in a
    single table.
    """
    _require_admin(current_user)

    files = sorted(
        _backup_dir().glob("*.db"),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    items = [_describe(p) for p in files]
    return {
        "backups":     items,
        "total":       len(items),
        # Shown on the page so the owner knows where the files physically are
        # if they ever need to copy them to a pen drive.
        "backup_dir":  str(_backup_dir()),
        "total_bytes": sum(i["size_bytes"] for i in items),
    }


@router.get("/download/{filename}", dependencies=[Depends(require_full_licence)])
def download_backup(filename: str, current_user: User = Depends(get_current_user)):
    """
    Download one backup.  This is how a copy gets OFF the shop PC and onto a
    pen drive or email — a backup sitting on the same disk as the database does
    not survive that disk failing.

    Pauses when the Curavo subscription has lapsed (require_full_licence).
    Taking backups - automatic and Backup Now - never does: a lapsed
    subscription must not put the shop's data at risk.
    """
    _require_admin(current_user)
    path = _safe_backup_path(filename)
    return FileResponse(
        path=str(path),
        filename=filename,
        media_type="application/octet-stream",
    )


@router.delete("/{filename}")
def delete_backup(filename: str, current_user: User = Depends(get_current_user)):
    """Delete one backup file.  Owner / Administrator only."""
    _require_admin(current_user)
    path = _safe_backup_path(filename)
    path.unlink()
    return {"message": f"Backup {filename} deleted."}
